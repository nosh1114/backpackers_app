// 国の画像URLを取得する関数
export const getCountryImageUrl = (countryName: string, width: number = 400): string => {
  const imageId = countryImageMap[countryName];
  
  if (imageId) {
    return `https://images.unsplash.com/${imageId}?auto=format&fit=crop&w=${width}&q=80`;
  }
  
  // マッピングにない場合はデフォルト画像（世界地図）
  return `https://images.unsplash.com/photo-1526778548025-fa2f459cd5c1?auto=format&fit=crop&w=${width}&q=80`;
};

// 国の背景画像URL（高解像度）を取得する関数
export const getCountryBackgroundUrl = (countryName: string): string => {
  return getCountryImageUrl(countryName, 1200);
};

